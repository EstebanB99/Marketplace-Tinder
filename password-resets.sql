CREATE TABLE PASSWORD_RESETS (
    TOKEN_HASH CHAR(64) NOT NULL PRIMARY KEY,
    USER_ID BIGINT UNSIGNED NOT NULL,
    EXPIRES_AT TIMESTAMP(6) NOT NULL,
    CREATED_AT TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    CONSTRAINT PASSWORD_RESETS_USER_FK FOREIGN KEY (USER_ID) REFERENCES APP_USERS (USER_ID) ON DELETE CASCADE,
    INDEX PASSWORD_RESETS_USER_IX (USER_ID),
    INDEX PASSWORD_RESETS_EXPIRY_IX (EXPIRES_AT)
) ENGINE=InnoDB;