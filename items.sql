CREATE TABLE APP_USERS (
    USER_ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    EMAIL VARCHAR(320) NOT NULL UNIQUE,
    PASSWORD_HASH VARCHAR(200) NOT NULL,
    CREATED_AT TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB;

CREATE TABLE ITEMS (
    ITEM_ID INT NOT NULL PRIMARY KEY,
    NAME VARCHAR(255) NOT NULL,
    DESCRIPTION VARCHAR(2000) NOT NULL,
    ADDRESS VARCHAR(255) NOT NULL,
    CITY VARCHAR(255) NOT NULL,
    STATE VARCHAR(100) NOT NULL,
    ZIPCODE VARCHAR(20) NOT NULL,
    IMAGE_URL VARCHAR(1000) NOT NULL,
    CREATED_AT TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB;

CREATE TABLE USER_ITEMS (
    USER_ID BIGINT UNSIGNED NOT NULL,
    ITEM_ID INT NOT NULL,
    NAME VARCHAR(255) NOT NULL,
    DESCRIPTION VARCHAR(2000) NOT NULL,
    ADDRESS VARCHAR(255) NOT NULL,
    CITY VARCHAR(255) NOT NULL,
    STATE VARCHAR(100) NOT NULL,
    ZIPCODE VARCHAR(20) NOT NULL,
    IMAGE_URL VARCHAR(1000) NOT NULL,
    STATUS VARCHAR(12) NOT NULL DEFAULT 'AVAILABLE',
    CREATED_AT TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    SHOWN_AT TIMESTAMP(6) NULL,
    PRIMARY KEY (USER_ID, ITEM_ID),
    CONSTRAINT USER_ITEMS_USER_FK FOREIGN KEY (USER_ID) REFERENCES APP_USERS (USER_ID) ON DELETE CASCADE,
    CONSTRAINT USER_ITEMS_ITEM_FK FOREIGN KEY (ITEM_ID) REFERENCES ITEMS (ITEM_ID),
    CONSTRAINT USER_ITEMS_STATUS_CK CHECK (STATUS IN ('AVAILABLE', 'SHOWN', 'KEPT')),
    INDEX USER_ITEMS_QUEUE_IX (USER_ID, STATUS, ITEM_ID)
) ENGINE=InnoDB;

CREATE TABLE USER_ITEM_HISTORY (
    USER_ID BIGINT UNSIGNED NOT NULL,
    ITEM_ID INT NOT NULL,
    STATUS VARCHAR(12) NOT NULL DEFAULT 'AVAILABLE',
    SHOWN_COUNT INT UNSIGNED NOT NULL DEFAULT 0,
    LAST_SHOWN_AT TIMESTAMP(6) NULL,
    CREATED_AT TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    UPDATED_AT TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (USER_ID, ITEM_ID),
    CONSTRAINT USER_ITEM_HISTORY_USER_FK FOREIGN KEY (USER_ID) REFERENCES APP_USERS (USER_ID) ON DELETE CASCADE,
    CONSTRAINT USER_ITEM_HISTORY_ITEM_FK FOREIGN KEY (ITEM_ID) REFERENCES ITEMS (ITEM_ID),
    CONSTRAINT USER_ITEM_HISTORY_STATUS_CK CHECK (STATUS IN ('AVAILABLE', 'SHOWN', 'KEPT', 'PASSED'))
) ENGINE=InnoDB;

CREATE TABLE USER_SESSIONS (
    TOKEN_HASH CHAR(64) NOT NULL PRIMARY KEY,
    USER_ID BIGINT UNSIGNED NOT NULL,
    EXPIRES_AT TIMESTAMP(6) NOT NULL,
    CREATED_AT TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    CONSTRAINT USER_SESSIONS_USER_FK FOREIGN KEY (USER_ID) REFERENCES APP_USERS (USER_ID) ON DELETE CASCADE,
    INDEX USER_SESSIONS_EXPIRY_IX (EXPIRES_AT)
) ENGINE=InnoDB;

